-- Séances de kiné / réathlétisation (Médical → 🦵 Kiné / Réathlé).
-- Reprend les colonnes de l'onglet « Saisie Séances » du classeur « Suivi kiné 26-27 U19N.xlsx ».
-- empreinte : identifiant d'une séance (date, joueuse, type, zone, kiné, observations) qui évite
-- les doublons quand le classeur est réimporté (kine_utils.empreinte).
create table if not exists seances_kine (
    id             bigint generated by default as identity primary key,
    date           date        not null,
    joueuse        text        not null,
    type_seance    text,
    zone           text,
    type_blessure  text,
    disponibilite  text,
    observations   text,
    kine           text,
    empreinte      text        unique,
    saisi_par      text,
    created_at     timestamptz not null default now()
);
create index if not exists seances_kine_joueuse_date on seances_kine (joueuse, date);

-- L'app écrit avec la clé service_role (RLS contourné) : RLS activé sans policy publique.
alter table seances_kine enable row level security;
